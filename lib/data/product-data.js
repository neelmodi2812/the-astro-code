export function getRelatedProducts(productId, category, lang = "gu", limit = 4) {
  const all = getAllProducts(lang)
  const sameCategory = all.filter(p => p.id !== productId && p.category === category)
  if (sameCategory.length >= limit) return sameCategory.slice(0, limit)
  const others = all.filter(p => p.id !== productId && p.category !== category)
  return [...sameCategory, ...others].slice(0, limit)
}
